"""Position tracking and PnL calculation model."""

from dataclasses import dataclass
from enum import Enum
from typing import Any
from engine.models.order import OrderSide


class PositionSide(str, Enum):
    LONG = "LONG"
    SHORT = "SHORT"
    FLAT = "FLAT"


@dataclass
class Position:
    """Tracks exposure, average entry price, and PnL for a specific asset."""

    symbol: str
    quantity: float = 0.0
    entry_price: float = 0.0
    current_price: float = 0.0
    realized_pnl: float = 0.0
    leverage: float = 1.0

    @property
    def side(self) -> PositionSide:
        if self.quantity > 1e-9:
            return PositionSide.LONG
        elif self.quantity < -1e-9:
            return PositionSide.SHORT
        return PositionSide.FLAT

    @property
    def is_open(self) -> bool:
        return self.side != PositionSide.FLAT

    @property
    def notional_value(self) -> float:
        """Current market value of the position."""
        return abs(self.quantity) * self.current_price

    @property
    def margin_required(self) -> float:
        """Margin required to hold this position."""
        if self.leverage <= 0:
            return self.notional_value
        return self.notional_value / self.leverage

    @property
    def unrealized_pnl(self) -> float:
        """Unrealized mark-to-market profit or loss."""
        if self.side == PositionSide.LONG:
            return (self.current_price - self.entry_price) * self.quantity
        elif self.side == PositionSide.SHORT:
            return (self.entry_price - self.current_price) * abs(self.quantity)
        return 0.0

    @property
    def unrealized_pnl_pct(self) -> float:
        """Unrealized return percentage relative to entry value."""
        if self.entry_price <= 0 or not self.is_open:
            return 0.0
        if self.side == PositionSide.LONG:
            return (self.current_price - self.entry_price) / self.entry_price
        else:
            return (self.entry_price - self.current_price) / self.entry_price

    def update_market_price(self, price: float) -> None:
        """Update current price from the latest bar."""
        if price > 0:
            self.current_price = price

    def apply_fill(self, side: OrderSide, fill_qty: float, fill_price: float) -> float:
        """Apply an executed trade to this position.

        Returns:
            Realized PnL generated by this trade.
        """
        fill_signed_qty = fill_qty if side == OrderSide.BUY else -fill_qty
        pnl = 0.0

        if self.side == PositionSide.FLAT:
            # Opening new position
            self.quantity = fill_signed_qty
            self.entry_price = fill_price
            self.current_price = fill_price
            return 0.0

        # Same direction: increase size
        if (self.side == PositionSide.LONG and fill_signed_qty > 0) or (
            self.side == PositionSide.SHORT and fill_signed_qty < 0
        ):
            new_qty = self.quantity + fill_signed_qty
            # Update weighted average entry price
            self.entry_price = (
                (self.entry_price * abs(self.quantity)) + (fill_price * abs(fill_signed_qty))
            ) / abs(new_qty)
            self.quantity = new_qty
            self.current_price = fill_price
            return 0.0

        # Opposite direction: reducing, closing, or flipping
        closing_qty = min(abs(self.quantity), abs(fill_signed_qty))
        if self.side == PositionSide.LONG:
            pnl = (fill_price - self.entry_price) * closing_qty
        else:  # SHORT
            pnl = (self.entry_price - fill_price) * closing_qty

        self.realized_pnl += pnl

        remaining_qty = self.quantity + fill_signed_qty

        if abs(remaining_qty) < 1e-9:
            # Fully closed
            self.quantity = 0.0
            self.entry_price = 0.0
        elif (self.side == PositionSide.LONG and remaining_qty < 0) or (
            self.side == PositionSide.SHORT and remaining_qty > 0
        ):
            # Flipped position
            self.quantity = remaining_qty
            self.entry_price = fill_price
        else:
            # Partially closed, entry price remains unchanged
            self.quantity = remaining_qty

        self.current_price = fill_price
        return pnl

    def to_dict(self) -> dict[str, Any]:
        return {
            "symbol": self.symbol,
            "side": self.side.value,
            "quantity": self.quantity,
            "entry_price": self.entry_price,
            "current_price": self.current_price,
            "notional_value": self.notional_value,
            "unrealized_pnl": self.unrealized_pnl,
            "unrealized_pnl_pct": self.unrealized_pnl_pct,
            "realized_pnl": self.realized_pnl,
            "leverage": self.leverage,
        }
